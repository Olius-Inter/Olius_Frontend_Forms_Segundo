// Opcional: requer playwright e @axe-core/playwright no ambiente de testes.
const { resolve } = require('node:path');
const { mkdir, writeFile } = require('node:fs/promises');
const assert = require('node:assert/strict');
const dependencyRoot = process.env.OLIUS_TEST_DEPENDENCIES || process.cwd();
const { chromium } = require(require.resolve('playwright', { paths: [dependencyRoot] }));
const { default: AxeBuilder } = require(require.resolve('@axe-core/playwright', { paths: [dependencyRoot] }));
const origin = process.env.OLIUS_TEST_URL || 'http://127.0.0.1:5185';
const output = resolve(__dirname, '../artifacts');
const key = 'olius.forms.deliveries.v1';

(async () => {
  await mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage();
  const errors = [], external = [], scans = [], requestedPaths = [];
  page.on('request', (request) => requestedPaths.push(new URL(request.url()).pathname));
  page.on('pageerror', (error) => errors.push(error.message));
  await context.route('**/*', (route) => {
    if (route.request().url().startsWith(origin + '/')) return route.continue();
    external.push(route.request().url()); return route.abort();
  });
  const records = () => page.evaluate((storageKey) => JSON.parse(localStorage.getItem(storageKey) || '[]'), key);
  const shot = async (name) => {
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.locator('img').evaluateAll((images) => images.every((image) => image.complete && image.naturalWidth > 0)), true);
    await page.screenshot({ path: resolve(output, `${name}.png`), fullPage: true });
  };
  const scan = async (name) => {
    const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    scans.push({ name, violations: result.violations });
    assert.equal(result.violations.length, 0, `Acessibilidade ${name}: ${JSON.stringify(result.violations.map((item) => ({ id: item.id, nodes: item.nodes.map((node) => node.target) })))}`);
  };
  const signIn = async (account) => {
    await page.locator('summary').click();
    await page.locator(`[data-account="${account}"]`).click();
    await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  };
  try {
    await page.goto(origin + '/');
    await page.getByRole('heading', { name: /Abra pelo aplicativo/ }).waitFor();
    assert.equal(await page.locator('#qr-code').count(), 0);
    assert.equal(await page.getByRole('link', { name: /QRs de demonstração/ }).count(), 0);
    assert.equal(await page.evaluate(() => typeof window.qrcode), 'undefined');
    await scan('entrada sem identificador');
    // Links antigos da tela removida continuam recebendo o participante, sem gerar QR.
    await page.goto(origin + '/?tela=qr&participante=b2c-001');
    await page.getByRole('heading', { name: /Como deseja/ }).waitFor();
    assert.equal(await page.locator('#qr-code').count(), 0);
    assert.equal(await page.getByRole('link', { name: /Copiar link do QR/ }).count(), 0);
    await page.goto(origin + '/?participante=b2c-001');
    await page.getByRole('heading', { name: /Como deseja/ }).waitFor();
    await shot('flow-selection-citizen'); await scan('escolha dos fluxos cidadão');
    assert.equal(await page.getByRole('link', { name: /Coleta com motorista/ }).count(), 0);
    assert.equal((await records()).length, 0);
    await page.getByRole('link', { name: /Entrega em PEV/ }).click();
    await page.getByRole('heading', { name: /Entre para confirmar/ }).waitFor();
    await shot('login-desktop'); await scan('login');
    await page.setViewportSize({ width: 390, height: 844 }); await shot('login-mobile');
    await page.getByLabel('E-mail', { exact: true }).fill('errado@olius.demo');
    await page.getByLabel('Senha', { exact: true }).fill('errada');
    await page.getByRole('button', { name: 'Continuar', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'E-mail ou senha incorretos' }).waitFor();
    await page.locator('summary').click();
    for (const [account, message] of [['access-no-pev', 'Somente o responsável'], ['access-pending', 'não está aprovado'], ['access-inactive', 'inativa']]) {
      await page.locator(`[data-account="${account}"]`).click();
      await page.getByRole('button', { name: 'Continuar', exact: true }).click();
      await page.getByRole('alert').filter({ hasText: message }).waitFor();
      assert.equal(await page.locator('#collection-form').count(), 0);
      assert.equal(await page.evaluate(() => sessionStorage.getItem('olius.forms.session.v1')), null);
      assert.equal((await records()).length, 0);
    }
    await shot('pev-access-denied-mobile'); await scan('bloqueio de acesso PEV');
    await page.locator('summary').click();
    // Simula um link direto com uma sessão local sem aprovação: a guarda também precisa negar.
    await page.evaluate(() => sessionStorage.setItem('olius.forms.session.v1', 'access-pending'));
    await page.reload();
    await page.getByRole('heading', { name: /Entre para confirmar/ }).waitFor();
    await page.getByRole('alert').filter({ hasText: 'não está aprovado' }).waitFor();
    assert.equal(await page.evaluate(() => sessionStorage.getItem('olius.forms.session.v1')), null);
    await signIn('op-001');
    await page.getByRole('heading', { name: 'Registrar entrega', exact: true }).waitFor();
    assert.equal((await records()).length, 0);
    await page.getByLabel('Qual a quantidade recebida?').fill('-1');
    await page.getByRole('button', { name: 'Confirmar recebimento' }).click();
    await page.getByRole('alert').waitFor();
    assert.equal((await records()).length, 0);
    await page.getByLabel('Qual a quantidade recebida?').fill('30');
    const draftBefore = await page.evaluate(() => sessionStorage.getItem('olius.forms.draft.b2c-001.op-001'));
    await page.reload();
    await page.getByRole('heading', { name: 'Registrar entrega', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Qual a quantidade recebida?').inputValue(), '30');
    assert.equal(await page.evaluate(() => sessionStorage.getItem('olius.forms.draft.b2c-001.op-001')), draftBefore);
    await shot('form-mobile'); await scan('formulário mobile');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1440, height: 1100 }); await shot('form-desktop');
    await page.locator('#collection-form').evaluate((form) => { form.requestSubmit(); form.requestSubmit(); });
    await page.getByRole('heading', { name: 'Cada gota conta.' }).waitFor();
    assert.equal((await records()).length, 1);
    await page.reload();
    await page.getByRole('heading', { name: 'Cada gota conta.' }).waitFor();
    assert.equal((await records()).length, 1);
    await shot('receipt-desktop'); await scan('comprovante');
    await page.goto(origin + '/?participante=b2c-001&fluxo=pev');
    await page.getByRole('heading', { name: 'Cada gota conta.' }).waitFor();
    await page.getByRole('button', { name: 'Novo recebimento' }).click();
    await page.getByLabel('Qual a quantidade recebida?').fill('30');
    await page.getByRole('button', { name: 'Confirmar recebimento' }).click();
    await page.getByRole('heading', { name: 'Cada gota conta.' }).waitFor();
    assert.equal((await records()).length, 2);
    await page.getByRole('button', { name: 'Novo recebimento' }).click();
    assert.equal(await page.getByRole('button', { name: 'Confirmar recebimento' }).isDisabled(), true);
    await page.setViewportSize({ width: 390, height: 844 }); await shot('daily-limit-mobile');
    await page.getByRole('link', { name: 'Histórico local', exact: true }).click();
    await page.getByRole('heading', { name: 'Histórico local', exact: true }).waitFor();
    assert.equal(await page.locator('.history-list li').count(), 2);
    await shot('history-mobile'); await scan('histórico');
    await page.getByRole('button', { name: 'Sair', exact: false }).click();
    await page.getByRole('heading', { name: /Abra pelo aplicativo/ }).waitFor();
    await page.goto(origin + '/?participante=b2c-001&fluxo=pev');
    await page.getByRole('heading', { name: /Entre para confirmar/ }).waitFor();
    await signIn('op-002');
    await page.goto(origin + '/?participante=b2c-001&fluxo=pev');
    assert.equal(await page.getByRole('button', { name: 'Confirmar recebimento' }).isEnabled(), true);
    assert.equal(await page.locator('.daily-info').innerText(), '0 de 2 registros neste PEV hoje');
    await page.goto(origin + '/?participante=invalido');
    await page.getByRole('heading', { name: 'Vamos tentar de novo?' }).waitFor();
    await page.goto(origin + '/?participante=b2c-001&fluxo=pev');
    await page.getByLabel('Qual a quantidade recebida?').fill('10');
    await page.evaluate((storageKey) => {
      const original = Storage.prototype.setItem;
      Storage.prototype.setItem = function (item, value) {
        if (item === storageKey) throw new DOMException('QuotaExceededError', 'QuotaExceededError');
        return original.call(this, item, value);
      };
    }, key);
    await page.getByRole('button', { name: 'Confirmar recebimento' }).click();
    await page.getByRole('alert').filter({ hasText: 'Nenhum recebimento foi confirmado' }).waitFor();
    assert.equal((await records()).length, 2);
    await page.setViewportSize({ width: 320, height: 700 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);

    // O mesmo QR de empresa pode seguir o PEV ou o fluxo da operadora.
    await page.goto(origin + '/?participante=b2b-001');
    await page.getByRole('heading', { name: /Como deseja/ }).waitFor();
    await shot('flow-selection-company-mobile'); await scan('escolha dos fluxos empresa');
    await page.getByRole('link', { name: /Entrega em PEV/ }).click();
    await page.getByRole('heading', { name: 'Registrar entrega', exact: true }).waitFor();
    assert.equal(await page.getByLabel('CPF do motorista').count(), 0);
    assert.equal(await page.getByLabel('CNH do motorista').count(), 0);
    assert.equal(await page.locator('#b2b-collection-form').count(), 0);
    assert.equal(await page.getByRole('heading', { name: 'Restaurante Sabor da Terra', exact: true }).count(), 1);
    await page.getByLabel('Qual a quantidade recebida?').fill('30');
    await shot('pev-company-mobile'); await scan('entrega B2B em PEV');
    await page.getByRole('button', { name: 'Confirmar recebimento' }).click();
    await page.getByRole('heading', { name: 'Cada gota conta.' }).waitFor();
    const pevCompany = (await records()).find((row) => row.participantId === 'b2b-001');
    assert.equal(pevCompany.flow, 'PEV'); assert.equal(pevCompany.liters, 30);
    assert.equal(await page.evaluate(() => localStorage.getItem('olius.forms.b2b.v1')), null);
    await page.getByRole('link', { name: 'Consultar histórico local' }).click();
    assert.equal(await page.locator('.history-list li').count(), 1);
    await page.goto(origin + '/?participante=b2b-001');
    await page.getByRole('link', { name: /Coleta com motorista/ }).click();
    await page.getByRole('heading', { name: /Identifique-se/ }).waitFor();
    assert.equal(await page.getByLabel('E-mail', { exact: true }).count(), 0);
    await shot('b2b-identification-mobile'); await scan('identificação do motorista');
    await page.getByLabel('CPF do motorista').fill('00000000000');
    await page.getByLabel('CNH do motorista').fill('00000000000');
    await page.getByRole('button', { name: 'Consultar solicitações', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Identificação operacional inválida' }).waitFor();
    const identifyDriver = async (driver = 'driver-demo-001') => {
      await page.locator('summary').click();
      await page.locator(`[data-driver="${driver}"]`).click();
      await page.getByRole('button', { name: 'Consultar solicitações', exact: true }).click();
    };
    // Details ainda estava fechado na tentativa anterior.
    await identifyDriver();
    await page.getByRole('heading', { name: /Qual solicitação/ }).waitFor();
    await shot('b2b-requests-mobile'); await scan('solicitações B2B');
    await page.getByRole('link', { name: 'Atender', exact: false }).first().click();
    await page.getByRole('heading', { name: 'Você chegou ao local?' }).waitFor();
    assert.equal(await page.locator('#b2b-collection-form').count(), 0);
    const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('olius.forms.b2b.v1') || '{"requests":[],"collections":[]}'));
    assert.equal((await state()).collections.length, 0);
    await page.getByRole('button', { name: 'Registrar chegada' }).click();
    await page.getByRole('heading', { name: 'Aguarde o aceite.' }).waitFor();
    assert.equal((await state()).collections.length, 0);
    assert.equal(await page.locator('#b2b-collection-form').count(), 0);
    await shot('b2b-waiting-mobile'); await scan('aguardando aceite');
    await page.getByText('Controles da apresentação', { exact: true }).click();
    await page.getByRole('button', { name: 'Simular aceite pelo estabelecimento' }).click();
    await page.getByRole('heading', { name: /Registrar resultado/ }).waitFor();
    await page.getByLabel('Óleo coletado (litros)', { exact: true }).fill('30');
    await page.getByRole('button', { name: 'Confirmar resultado da coleta' }).click();
    await page.getByRole('alert').waitFor();
    assert.equal((await state()).collections.length, 0);
    await page.getByLabel('Óleo apresentado (litros)', { exact: true }).fill('30');
    await page.getByLabel('Condição do óleo', { exact: true }).selectOption('ACCEPTABLE');
    await page.getByLabel('Houve ocorrência comprometedora?', { exact: true }).selectOption('false');
    await shot('b2b-form-mobile'); await scan('resultado da coleta B2B');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1440, height: 1100 }); await shot('b2b-form-desktop');
    await page.locator('#b2b-collection-form').evaluate((form) => { form.requestSubmit(); form.requestSubmit(); });
    await page.getByRole('heading', { name: 'Visita registrada.' }).waitFor();
    const firstRecord = (await state()).collections[0];
    assert.equal(firstRecord.result, 'SUCCESSFUL'); assert.equal((await state()).collections.length, 1);
    await shot('b2b-receipt-desktop'); await scan('comprovante B2B');
    await page.reload();
    await page.getByRole('heading', { name: /Identifique-se/ }).waitFor();
    await identifyDriver();
    await page.getByRole('heading', { name: 'Visita registrada.' }).waitFor();
    assert.equal((await state()).collections.length, 1);
    await page.getByRole('link', { name: 'Voltar às solicitações' }).click();
    assert.equal(await page.getByRole('link', { name: 'Atender', exact: false }).count(), 1);
    await page.getByRole('link', { name: 'Atender', exact: false }).click();
    await page.getByRole('button', { name: 'Registrar chegada' }).click();
    await page.getByText('Controles da apresentação', { exact: true }).click();
    await page.getByRole('button', { name: 'Simular aceite pelo estabelecimento' }).click();
    await page.getByLabel('Óleo apresentado (litros)', { exact: true }).fill('0');
    await page.getByLabel('Óleo coletado (litros)', { exact: true }).fill('0');
    await page.getByLabel('Condição do óleo', { exact: true }).selectOption('NOT_ASSESSED');
    await page.getByLabel('Houve ocorrência comprometedora?', { exact: true }).selectOption('false');
    await page.getByRole('button', { name: 'Confirmar resultado da coleta' }).click();
    await page.getByRole('alert').filter({ hasText: 'observação' }).waitFor();
    await page.getByLabel('Observação', { exact: true }).fill('Não havia óleo disponível na visita de demonstração.');
    await page.getByLabel('Volume fora da tolerância do pedido').check();
    await page.getByRole('button', { name: 'Confirmar resultado da coleta' }).click();
    await page.getByRole('heading', { name: 'Visita registrada.' }).waitFor();
    assert.equal((await state()).collections.length, 2);
    assert.equal((await state()).collections[1].result, 'UNSUCCESSFUL');
    assert.equal((await state()).collections[1].collectedVolumeLiters, 0);
    await page.getByRole('link', { name: 'Comprovantes locais', exact: true }).click();
    await page.getByRole('heading', { name: 'Comprovantes locais', exact: true }).waitFor();
    assert.equal(await page.locator('.history-list li').count(), 2);
    await page.setViewportSize({ width: 390, height: 844 }); await shot('b2b-history-mobile');
    const persisted = await page.evaluate(() => localStorage.getItem('olius.forms.b2b.v1'));
    assert.equal(persisted.includes('12345678901'), false);
    await page.getByRole('button', { name: 'Encerrar', exact: true }).click();
    await page.getByRole('heading', { name: /Identifique-se/ }).waitFor();
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
    assert.equal(requestedPaths.some((path) => path.includes('qrcode.js')), false);
    assert.equal(await page.getByRole('link', { name: /QRs de demonstração/ }).count(), 0);
    console.log('Entrada pelo link do mobile sem geração de QR; identificação preservada, PEV B2B/B2C e motorista: OK.');
  } finally {
    await writeFile(resolve(output, 'browser-report.json'), JSON.stringify({ errors, external, scans }, null, 2));
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
